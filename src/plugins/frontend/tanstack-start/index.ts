import { helloCall } from '../../../engine/client'
import { PNPM_BUILD_STAGE } from '../../../engine/docker'
import { byName, camelCase, pascalCase, upperSnake } from '../../../engine/names'
import { json, readPluginFiles } from '../../../engine/tree'
import type { AppContext, FileTree, FrameworkPlugin, ResolvedApp } from '../../types'

const urlVar = (b: ResolvedApp) => `${upperSnake(b.name)}_URL`
const clientVar = (b: ResolvedApp) => `${camelCase(b.name)}Client`

function apiFile(ctx: AppContext): string {
  if (ctx.backends.length === 0) {
    return '// Generated by octorepo. Do not edit: regenerated by `add`.\nexport {}\n'
  }
  const imports = byName(ctx.backends).map(
    (b) =>
      `import { createClient as create${pascalCase(b.name)} } from '${ctx.scope}/${b.name}-client'`,
  )
  const clients = byName(ctx.backends).map(
    (b) => `const ${camelCase(b.name)}Url = process.env.${urlVar(b)} ?? 'http://localhost:${b.port}'
export const ${clientVar(b)} = create${pascalCase(b.name)}(${camelCase(b.name)}Url)`,
  )
  return `// Generated by octorepo. Do not edit: regenerated by \`add\`.
// Server-side only: imported from server functions, so backend URLs come from runtime env and
// never reach the browser bundle.
${imports.join('\n')}

${clients.join('\n\n')}
`
}

function indexRoute(ctx: AppContext): string {
  if (ctx.backends.length === 0) {
    return `import { Card } from '${ctx.scope}/ui-react'
import { createFileRoute } from '@tanstack/react-router'

export const Route = createFileRoute('/')({ component: Home })

function Home() {
  return (
    <main>
      <h1>${ctx.app.name}</h1>
      <Card title="${ctx.app.name}">Hello from ${ctx.app.name}</Card>
    </main>
  )
}
`
  }
  const clientImports = byName(ctx.backends).map(clientVar).join(', ')
  const calls = byName(ctx.backends)
    .map((b) => helloCall(b.name, clientVar(b)))
    .join('\n')
  return `import { Card } from '${ctx.scope}/ui-react'
import { createFileRoute } from '@tanstack/react-router'
import { createServerFn } from '@tanstack/react-start'
import { ${clientImports} } from '../generated/api'
import { type CardProps, toCard } from '../lib/cards'

async function hello(
  name: string,
  call: (signal: AbortSignal) => Promise<{ data?: { message: string }; error?: unknown }>,
): Promise<CardProps> {
  try {
    // Bounded, so a hanging backend renders "unreachable" instead of stalling the page.
    const { data, error } = await call(AbortSignal.timeout(3000))
    return toCard({ name, data, error })
  } catch (error) {
    return toCard({ name, error })
  }
}

// A server function: backends are called on the server per request, never at build time.
const loadCards = createServerFn({ method: 'GET' }).handler(() =>
  Promise.all([
${calls}
  ]),
)

export const Route = createFileRoute('/')({
  loader: () => loadCards(),
  component: Home,
})

function Home() {
  const cards = Route.useLoaderData()
  return (
    <main>
      <h1>${ctx.app.name}</h1>
      {cards.map((card) => (
        <Card key={card.title} title={card.title}>
          {card.body}
        </Card>
      ))}
    </main>
  )
}
`
}

function generate(ctx: AppContext): FileTree {
  const { app, scope, versions: v, backends } = ctx
  const dir = `apps/${app.name}`
  const files = readPluginFiles(new URL('./', import.meta.url), {
    name: app.name,
    scope,
    port: String(app.port),
  })
  const tree: FileTree = {}
  for (const [path, content] of Object.entries(files)) tree[`${dir}/${path}`] = content
  tree[`${dir}/src/routes/index.tsx`] = indexRoute(ctx)
  tree[`${dir}/src/generated/api.ts`] = apiFile(ctx)
  tree[`${dir}/.env.example`] =
    `${backends.map((b) => `${urlVar(b)}=http://localhost:${b.port}`).join('\n')}${backends.length > 0 ? '\n' : ''}`
  // No `files` field: the Docker image copies the self-contained .output/ instead of `pnpm deploy` (R15).
  tree[`${dir}/package.json`] = json({
    name: `${scope}/${app.name}`,
    version: '0.0.0',
    private: true,
    type: 'module',
    scripts: {
      dev: `vite dev --port ${app.port}`,
      build: 'vite build',
      start: 'node .output/server/index.mjs',
      lint: 'biome check .',
      typecheck: 'tsc --noEmit',
      test: 'vitest run',
    },
    dependencies: {
      [`${scope}/ui-react`]: 'workspace:*',
      ...Object.fromEntries(backends.map((b) => [`${scope}/${b.name}-client`, 'workspace:*'])),
      '@tanstack/react-router': v['@tanstack/react-router'],
      '@tanstack/react-start': v['@tanstack/react-start'],
      react: v.react,
      'react-dom': v['react-dom'],
    },
    devDependencies: {
      [`${scope}/config`]: 'workspace:*',
      '@biomejs/biome': v['@biomejs/biome'],
      '@types/node': v['@types/node'],
      '@types/react': v['@types/react'],
      '@types/react-dom': v['@types/react-dom'],
      '@vitejs/plugin-react': v['@vitejs/plugin-react'],
      nitro: v.nitro,
      typescript: v.typescript,
      vite: v.vite,
      vitest: v.vitest,
    },
  })
  return tree
}

function dockerfile(ctx: AppContext): string {
  const pkg = `${ctx.scope}/${ctx.app.name}`
  const dir = `apps/${ctx.app.name}`
  const port = ctx.app.port
  // nitro bundles the server and its traced dependencies into .output/, so it runs without node_modules.
  return `${PNPM_BUILD_STAGE}RUN pnpm --filter ${pkg}... build

FROM node:24-alpine AS runtime
ENV NODE_ENV=production
ENV PORT=${port}
ENV HOST=0.0.0.0
WORKDIR /app
COPY --from=build --chown=node:node /repo/${dir}/.output ./.output
USER node
EXPOSE ${port}
HEALTHCHECK --interval=30s --timeout=3s --start-period=10s CMD node -e "fetch('http://127.0.0.1:' + process.env.PORT + '/').then((r) => process.exit(r.ok ? 0 : 1)).catch(() => process.exit(1))"
CMD ["node",".output/server/index.mjs"]
`
}

