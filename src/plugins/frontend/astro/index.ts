import { PNPM_BUILD_STAGE } from '../../../engine/docker'
import { camelCase, pascalCase, upperSnake } from '../../../engine/names'
import { json, readPluginFiles } from '../../../engine/tree'
import type { AppContext, FileTree, FrameworkPlugin, ResolvedApp } from '../../types'

const urlVar = (b: ResolvedApp) => `${upperSnake(b.name)}_URL`
const clientVar = (b: ResolvedApp) => `${camelCase(b.name)}Client`

function apiFile(ctx: AppContext): string {
  if (ctx.backends.length === 0) {
    return '// Generated by octorepo. Do not edit: regenerated by `add`.\nexport {}\n'
  }
  const imports = ctx.backends.map(
    (b) =>
      `import { createClient as create${pascalCase(b.name)} } from '${ctx.scope}/${b.name}-client'`,
  )
  const clients = ctx.backends.map(
    (b) => `const ${camelCase(b.name)}Url = process.env.${urlVar(b)} ?? 'http://localhost:${b.port}'
export const ${clientVar(b)} = create${pascalCase(b.name)}(${camelCase(b.name)}Url)`,
  )
  // process.env (not import.meta.env, which Vite inlines at build time) keeps the URLs runtime config.
  return `// Generated by octorepo. Do not edit: regenerated by \`add\`.
// Server-side only: backend URLs come from runtime env and are never exposed to the browser.
${imports.join('\n')}

${clients.join('\n\n')}
`
}

function layout(ctx: AppContext, body: string): string {
  return `<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width" />
    <title>${ctx.app.name}</title>
  </head>
  <body>
    <main>
      <h1>${ctx.app.name}</h1>
${body}
    </main>
  </body>
</html>
`
}

function pageFile(ctx: AppContext): string {
  if (ctx.backends.length === 0) {
    return `---
import Card from '../components/Card.astro'
---

${layout(ctx, `      <Card title="${ctx.app.name}">Hello from ${ctx.app.name}</Card>`)}`
  }
  const clientImports = ctx.backends.map(clientVar).join(', ')
  const calls = ctx.backends
    .map((b) => `    hello('${b.name}', () => ${clientVar(b)}.GET('/hello')),`)
    .join('\n')
  return `---
import Card from '../components/Card.astro'
import { ${clientImports} } from '../generated/api'
import { type BackendResult, toCard } from '../lib/cards'

// output: 'server' renders this page per request, so backends are only called at runtime.
async function hello(
  name: string,
  call: () => Promise<{ data?: { message: string }; error?: unknown }>,
): Promise<BackendResult> {
  try {
    const { data, error } = await call()
    return { name, data, error }
  } catch (error) {
    return { name, error }
  }
}

const cards = (
  await Promise.all([
${calls}
  ])
).map(toCard)
---

${layout(ctx, '      {cards.map((card) => <Card title={card.title}>{card.body}</Card>)}')}`
}

function generate(ctx: AppContext): FileTree {
  const { app, scope, versions: v, backends } = ctx
  const dir = `apps/${app.name}`
  const files = readPluginFiles(new URL('./', import.meta.url), {
    name: app.name,
    scope,
    port: String(app.port),
  })
  const tree: FileTree = {}
  for (const [path, content] of Object.entries(files)) tree[`${dir}/${path}`] = content
  tree[`${dir}/src/pages/index.astro`] = pageFile(ctx)
  tree[`${dir}/src/generated/api.ts`] = apiFile(ctx)
  tree[`${dir}/.env.example`] =
    `${backends.map((b) => `${urlVar(b)}=http://localhost:${b.port}`).join('\n')}${backends.length > 0 ? '\n' : ''}`
  tree[`${dir}/package.json`] = json({
    name: `${scope}/${app.name}`,
    version: '0.0.0',
    private: true,
    type: 'module',
    // The Docker image is assembled with `pnpm deploy`, which ships only these files.
    files: ['dist'],
    scripts: {
      // --ignore-lock keeps the server in the foreground: Astro otherwise detaches it when it
      // detects an AI agent, escaping the monorepo runner that owns `dev`.
      dev: `astro dev --port ${app.port} --ignore-lock`,
      build: 'astro build',
      start: 'node dist/server/entry.mjs',
      lint: 'biome check .',
      typecheck: 'astro check',
      test: 'vitest run',
    },
    dependencies: {
      ...Object.fromEntries(backends.map((b) => [`${scope}/${b.name}-client`, 'workspace:*'])),
      '@astrojs/node': v['@astrojs/node'],
      astro: v.astro,
    },
    devDependencies: {
      [`${scope}/config`]: 'workspace:*',
      '@astrojs/check': v['@astrojs/check'],
      '@biomejs/biome': v['@biomejs/biome'],
      '@types/node': v['@types/node'],
      typescript: v.typescript,
      vitest: v.vitest,
    },
  })
  return tree
}

function dockerfile(ctx: AppContext): string {
  const pkg = `${ctx.scope}/${ctx.app.name}`
  const port = ctx.app.port
  // The standalone server imports its dependencies at runtime, so the image needs a pruned node_modules.
  return `${PNPM_BUILD_STAGE}RUN pnpm --filter ${pkg}... build
RUN pnpm deploy --filter ${pkg} --prod --legacy /out

FROM node:24-alpine AS runtime
ENV NODE_ENV=production
ENV PORT=${port}
ENV HOST=0.0.0.0
WORKDIR /app
COPY --from=build --chown=node:node /out ./
USER node
EXPOSE ${port}
HEALTHCHECK --interval=30s --timeout=3s --start-period=10s CMD node -e "fetch('http://127.0.0.1:' + process.env.PORT + '/').then((r) => process.exit(r.ok ? 0 : 1)).catch(() => process.exit(1))"
CMD ["node","dist/server/entry.mjs"]
`
}

