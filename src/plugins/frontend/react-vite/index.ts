import { PNPM_BUILD_STAGE } from '../../../engine/docker'
import { camelCase, pascalCase, upperSnake } from '../../../engine/names'
import { json, readPluginFiles } from '../../../engine/tree'
import type { AppContext, FileTree, FrameworkPlugin, ResolvedApp } from '../../types'

const clientVar = (b: ResolvedApp) => `${camelCase(b.name)}Client`
const byName = (a: ResolvedApp, b: ResolvedApp) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0)

function generatedApi(ctx: AppContext): string {
  if (ctx.backends.length === 0) return 'export {}\n'
  const sorted = [...ctx.backends].sort(byName)
  const imports = sorted
    .map(
      (b) =>
        `import { createClient as create${pascalCase(b.name)}Client } from '${ctx.scope}/${b.name}-client'`,
    )
    .join('\n')
  const clients = sorted
    .map(
      (b) =>
        `const ${camelCase(b.name)}Url = import.meta.env.VITE_${upperSnake(b.name)}_URL ?? 'http://localhost:${b.port}'
export const ${clientVar(b)} = create${pascalCase(b.name)}Client(${camelCase(b.name)}Url)`,
    )
    .join('\n\n')
  return `// Generated by octorepo. Do not edit.\n${imports}\n\n${clients}\n`
}

function appTsx(ctx: AppContext): string {
  const backends = [...ctx.backends].sort(byName)
  if (backends.length === 0) {
    return `import { Card } from '${ctx.scope}/ui-react'

export function App() {
  return <Card title="${ctx.app.name}">Hello from ${ctx.app.name}</Card>
}
`
  }
  const clientNames = backends.map(clientVar).sort().join(', ')
  const loaders = backends
    .map(
      (b) => `async function load${pascalCase(b.name)}(): Promise<string> {
  const { data } = await ${clientVar(b)}.GET('/hello')
  return data?.message ?? 'No response'
}`,
    )
    .join('\n\n')
  const cards = backends
    .map((b) => `      <BackendCard title="${b.name}" load={load${pascalCase(b.name)}} />`)
    .join('\n')
  return `import { Card } from '${ctx.scope}/ui-react'
import { useEffect, useState } from 'react'
import { ${clientNames} } from './generated/api'

${loaders}

function BackendCard({ title, load }: { title: string; load: () => Promise<string> }) {
  const [message, setMessage] = useState('Loading...')
  useEffect(() => {
    let cancelled = false
    load()
      .then((m) => {
        if (!cancelled) setMessage(m)
      })
      .catch(() => {
        if (!cancelled) setMessage('Backend unreachable')
      })
    return () => {
      cancelled = true
    }
  }, [load])
  return <Card title={title}>{message}</Card>
}

export function App() {
  return (
    <main>
${cards}
    </main>
  )
}
`
}

function appTest(ctx: AppContext): string {
  const backends = [...ctx.backends].sort(byName)
  if (backends.length === 0) {
    return `import { render, screen } from '@testing-library/react'
import { expect, it } from 'vitest'
import { App } from './App'

it('renders the card', () => {
  render(<App />)
  expect(screen.getByText('Hello from ${ctx.app.name}')).toBeTruthy()
})
`
  }
  const mocks = backends
    .map(
      (b) =>
        `  ${clientVar(b)}: {\n    GET: vi.fn().mockResolvedValue({ data: { message: 'Hello from ${b.name}' } }),\n  },`,
    )
    .join('\n')
  const asserts = backends
    .map((b) => `  expect(await screen.findByText('Hello from ${b.name}')).toBeTruthy()`)
    .join('\n')
  return `import { render, screen } from '@testing-library/react'
import { expect, it, vi } from 'vitest'
import { App } from './App'

vi.mock('./generated/api', () => ({
${mocks}
}))

it('renders the hello message of each backend', async () => {
  render(<App />)
${asserts}
})
`
}

function generate(ctx: AppContext): FileTree {
  const { app, scope, versions: v, backends } = ctx
  const dir = `apps/${app.name}`
  const files = readPluginFiles(new URL('./', import.meta.url), {
    name: app.name,
    scope,
    port: String(app.port),
  })
  const tree: FileTree = {}
  for (const [path, content] of Object.entries(files)) tree[`${dir}/${path}`] = content
  tree[`${dir}/package.json`] = json({
    name: `${scope}/${app.name}`,
    version: '0.0.0',
    private: true,
    type: 'module',
    files: ['dist'],
    scripts: {
      dev: `vite --port ${app.port}`,
      build: 'vite build',
      lint: 'biome check .',
      typecheck: 'tsc --noEmit',
      test: 'vitest run',
    },
    dependencies: {
      [`${scope}/ui-react`]: 'workspace:*',
      ...Object.fromEntries(backends.map((b) => [`${scope}/${b.name}-client`, 'workspace:*'])),
      react: v.react,
      'react-dom': v['react-dom'],
    },
    devDependencies: {
      [`${scope}/config`]: 'workspace:*',
      '@biomejs/biome': v['@biomejs/biome'],
      '@testing-library/dom': v['@testing-library/dom'],
      '@testing-library/react': v['@testing-library/react'],
      '@types/react': v['@types/react'],
      '@types/react-dom': v['@types/react-dom'],
      '@vitejs/plugin-react': v['@vitejs/plugin-react'],
      jsdom: v.jsdom,
      typescript: v.typescript,
      vite: v.vite,
      vitest: v.vitest,
    },
  })
  tree[`${dir}/src/generated/api.ts`] = generatedApi(ctx)
  tree[`${dir}/src/App.tsx`] = appTsx(ctx)
  tree[`${dir}/src/App.test.tsx`] = appTest(ctx)
  tree[`${dir}/.env.example`] = backends
    .map((b) => `VITE_${upperSnake(b.name)}_URL=http://localhost:${b.port}\n`)
    .join('')
  return tree
}

function dockerfile(ctx: AppContext): string {
  const pkg = `${ctx.scope}/${ctx.app.name}`
  const args = ctx.backends
    .map((b) => {
      const n = `VITE_${upperSnake(b.name)}_URL`
      return `ARG ${n}=http://localhost:${b.port}\nENV ${n}=$${n}\n`
    })
    .join('')
  return `${PNPM_BUILD_STAGE}${args}RUN pnpm --filter ${pkg}... build

FROM nginx:alpine AS runtime
COPY apps/${ctx.app.name}/nginx.conf /etc/nginx/conf.d/default.conf
COPY --from=build /repo/apps/${ctx.app.name}/dist /usr/share/nginx/html
EXPOSE ${ctx.app.port}
`
}

