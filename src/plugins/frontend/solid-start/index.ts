import { PNPM_BUILD_STAGE } from '../../../engine/docker'
import { camelCase, pascalCase, upperSnake } from '../../../engine/names'
import { json, readPluginFiles } from '../../../engine/tree'
import type { AppContext, FileTree, FrameworkPlugin, ResolvedApp } from '../../types'

const urlVar = (b: ResolvedApp) => `${upperSnake(b.name)}_URL`
const clientVar = (b: ResolvedApp) => `${camelCase(b.name)}Client`

function apiFile(ctx: AppContext): string {
  if (ctx.backends.length === 0) {
    return '// Generated by octorepo. Do not edit: regenerated by `add`.\nexport {}\n'
  }
  const imports = ctx.backends.map(
    (b) =>
      `import { createClient as create${pascalCase(b.name)} } from '${ctx.scope}/${b.name}-client'`,
  )
  const clients = ctx.backends.map(
    (b) => `const ${camelCase(b.name)}Url = process.env.${urlVar(b)} ?? 'http://localhost:${b.port}'
export const ${clientVar(b)} = create${pascalCase(b.name)}(${camelCase(b.name)}Url)`,
  )
  return `// Generated by octorepo. Do not edit: regenerated by \`add\`.
// Server-side only (imported from a "use server" module): backend URLs come from runtime env.
${imports.join('\n')}

${clients.join('\n\n')}
`
}

/** A "use server" module: the client bundle only gets an RPC stub, so the clients stay server-side. */
function helloFile(ctx: AppContext): string {
  const calls = ctx.backends.map((b) => `hello('${b.name}', () => ${clientVar(b)}.GET('/hello'))`)
  // Matches biome's formatting: one line when it fits in 100 columns, else one call per line.
  const oneLine = `  const results = await Promise.all([${calls.join(', ')}])`
  const all =
    oneLine.length <= 100
      ? oneLine
      : `  const results = await Promise.all([\n${calls.map((c) => `    ${c},`).join('\n')}\n  ])`
  return `'use server'
import { ${ctx.backends.map(clientVar).join(', ')} } from '../generated/api'
import { type BackendResult, type CardProps, toCard } from './cards'

async function hello(
  name: string,
  call: () => Promise<{ data?: { message: string }; error?: unknown }>,
): Promise<BackendResult> {
  try {
    const { data, error } = await call()
    return { name, data, error }
  } catch (error) {
    return { name, error }
  }
}

/** Calls each backend's /hello per request; a failed call becomes an "unreachable" card. */
export async function getHellos(): Promise<CardProps[]> {
${all}
  return results.map(toCard)
}
`
}

function pageFile(ctx: AppContext): string {
  if (ctx.backends.length === 0) {
    return `import { Card } from '${ctx.scope}/ui-solid'

export default function Home() {
  return (
    <main>
      <h1>${ctx.app.name}</h1>
      <Card title="${ctx.app.name}">Hello from ${ctx.app.name}</Card>
    </main>
  )
}
`
  }
  return `import { Card } from '${ctx.scope}/ui-solid'
import { createAsync, query } from '@solidjs/router'
import { For } from 'solid-js'
import { getHellos } from '../lib/hello'

// Runs on the server at request time, so the build never needs the backends to be reachable.
const hellos = query(() => getHellos(), 'hellos')

export default function Home() {
  // deferStream keeps the backend messages in the initial server-rendered HTML.
  const cards = createAsync(() => hellos(), { deferStream: true })
  return (
    <main>
      <h1>${ctx.app.name}</h1>
      <For each={cards()}>{(card) => <Card title={card.title}>{card.body}</Card>}</For>
    </main>
  )
}
`
}

function generate(ctx: AppContext): FileTree {
  const { app, scope, versions: v, backends } = ctx
  const dir = `apps/${app.name}`
  const files = readPluginFiles(new URL('./', import.meta.url), { name: app.name, scope })
  const tree: FileTree = {}
  for (const [path, content] of Object.entries(files)) tree[`${dir}/${path}`] = content
  tree[`${dir}/src/routes/index.tsx`] = pageFile(ctx)
  tree[`${dir}/src/generated/api.ts`] = apiFile(ctx)
  if (backends.length > 0) tree[`${dir}/src/lib/hello.ts`] = helloFile(ctx)
  tree[`${dir}/.env.example`] =
    `${backends.map((b) => `${urlVar(b)}=http://localhost:${b.port}`).join('\n')}${backends.length > 0 ? '\n' : ''}`
  tree[`${dir}/package.json`] = json({
    name: `${scope}/${app.name}`,
    version: '0.0.0',
    private: true,
    type: 'module',
    scripts: {
      dev: `vite dev --port ${app.port}`,
      build: 'vite build',
      start: 'node .output/server/index.mjs',
      lint: 'biome check .',
      typecheck: 'tsc --noEmit',
      test: 'vitest run',
    },
    dependencies: {
      [`${scope}/ui-solid`]: 'workspace:*',
      ...Object.fromEntries(backends.map((b) => [`${scope}/${b.name}-client`, 'workspace:*'])),
      '@solidjs/meta': v['@solidjs/meta'],
      '@solidjs/router': v['@solidjs/router'],
      '@solidjs/start': v['@solidjs/start'],
      'solid-js': v['solid-js'],
    },
    devDependencies: {
      [`${scope}/config`]: 'workspace:*',
      '@biomejs/biome': v['@biomejs/biome'],
      '@types/node': v['@types/node'],
      nitro: v.nitro,
      typescript: v.typescript,
      vite: v.vite,
      vitest: v.vitest,
    },
  })
  return tree
}

function dockerfile(ctx: AppContext): string {
  const pkg = `${ctx.scope}/${ctx.app.name}`
  const dir = `apps/${ctx.app.name}`
  const port = ctx.app.port
  // nitro's node preset bundles the server and its dependencies into a self-contained .output/.
  return `${PNPM_BUILD_STAGE}RUN pnpm --filter ${pkg}... build

FROM node:24-alpine AS runtime
ENV NODE_ENV=production
ENV PORT=${port}
ENV HOST=0.0.0.0
WORKDIR /app
COPY --from=build --chown=node:node /repo/${dir}/.output ./.output
USER node
EXPOSE ${port}
HEALTHCHECK --interval=30s --timeout=3s --start-period=10s CMD node -e "fetch('http://127.0.0.1:' + process.env.PORT + '/').then((r) => process.exit(r.ok ? 0 : 1)).catch(() => process.exit(1))"
CMD ["node",".output/server/index.mjs"]
`
}

