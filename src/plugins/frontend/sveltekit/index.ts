import { helloCall } from '../../../engine/client'
import { PNPM_BUILD_STAGE } from '../../../engine/docker'
import { camelCase, pascalCase, upperSnake } from '../../../engine/names'
import { json, readPluginFiles } from '../../../engine/tree'
import type { AppContext, FileTree, FrameworkPlugin, ResolvedApp } from '../../types'

const HEADER = '// Generated by octorepo. Do not edit: regenerated by `add`.'
const urlVar = (b: ResolvedApp) => `${upperSnake(b.name)}_URL`
const clientVar = (b: ResolvedApp) => `${camelCase(b.name)}Client`
const byName = (a: ResolvedApp, b: ResolvedApp) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0)

/**
 * SvelteKit 3 declares env vars in `src/env.ts`. Non-static private vars are read from the
 * environment when the server starts (never inlined at build) and exposed via `$app/env/private`.
 */
function envFile(backends: ResolvedApp[]): string {
  const vars = backends.map(
    (b) => `  ${urlVar(b)}: {
    description: 'Base URL of the ${b.name} backend',
    schema: (value) => value || 'http://localhost:${b.port}',
  },`,
  )
  return `${HEADER}
import { defineEnvVars } from '@sveltejs/kit/env'

export const variables = defineEnvVars({
${vars.join('\n')}
})
`
}

function apiFile(ctx: AppContext): string {
  const backends = [...ctx.backends].sort(byName)
  if (backends.length === 0) return `${HEADER}\nexport {}\n`
  const imports = backends.map(
    (b) =>
      `import { createClient as create${pascalCase(b.name)} } from '${ctx.scope}/${b.name}-client'`,
  )
  const clients = backends.map(
    (b) => `export const ${clientVar(b)} = create${pascalCase(b.name)}(${urlVar(b)})`,
  )
  return `${HEADER}
// Server-side only: backend URLs come from runtime env and are never exposed to the browser.
${imports.join('\n')}
import { ${backends.map(urlVar).join(', ')} } from '$app/env/private'

${clients.join('\n')}
`
}

function pageServerFile(ctx: AppContext): string {
  const backends = [...ctx.backends].sort(byName)
  const calls = backends.map((b) => helloCall(b.name, clientVar(b))).join('\n')
  return `import { ${backends.map(clientVar).join(', ')} } from '../generated/api'
import { type BackendResult, toCard } from '../lib/cards'
import type { PageServerLoad } from './$types'

async function hello(
  name: string,
  call: (signal: AbortSignal) => Promise<{ data?: { message: string }; error?: unknown }>,
): Promise<BackendResult> {
  try {
    // Bounded, so a hanging backend renders "unreachable" instead of stalling the page.
    const { data, error } = await call(AbortSignal.timeout(3000))
    return { name, data, error }
  } catch (error) {
    return { name, error }
  }
}

// Runs per request on the server (pages are not prerendered), so the build never needs the backends.
export const load: PageServerLoad = async () => {
  const results = await Promise.all([
${calls}
  ])
  return { cards: results.map(toCard) }
}
`
}

function pageFile(ctx: AppContext): string {
  if (ctx.backends.length === 0) {
    return `<script lang="ts">
  import { Card } from '${ctx.scope}/ui-svelte'
</script>

<main>
  <h1>${ctx.app.name}</h1>
  <Card title="${ctx.app.name}">Hello from ${ctx.app.name}</Card>
</main>
`
  }
  return `<script lang="ts">
  import { Card } from '${ctx.scope}/ui-svelte'
  import type { PageProps } from './$types'

  const { data }: PageProps = $props()
</script>

<main>
  <h1>${ctx.app.name}</h1>
  {#each data.cards as card (card.title)}
    <Card title={card.title}>{card.body}</Card>
  {/each}
</main>
`
}

function generate(ctx: AppContext): FileTree {
  const { app, scope, versions: v } = ctx
  const backends = [...ctx.backends].sort(byName)
  const dir = `apps/${app.name}`
  const files = readPluginFiles(new URL('./', import.meta.url), { name: app.name, scope })
  const tree: FileTree = {}
  for (const [path, content] of Object.entries(files)) tree[`${dir}/${path}`] = content
  tree[`${dir}/src/routes/+page.svelte`] = pageFile(ctx)
  tree[`${dir}/src/generated/api.ts`] = apiFile(ctx)
  if (backends.length > 0) {
    tree[`${dir}/src/routes/+page.server.ts`] = pageServerFile(ctx)
    tree[`${dir}/src/env.ts`] = envFile(backends)
  }
  tree[`${dir}/.env.example`] =
    `${backends.map((b) => `${urlVar(b)}=http://localhost:${b.port}`).join('\n')}${backends.length > 0 ? '\n' : ''}`
  tree[`${dir}/package.json`] = json({
    name: `${scope}/${app.name}`,
    version: '0.0.0',
    private: true,
    type: 'module',
    scripts: {
      dev: `vite dev --port ${app.port}`,
      build: 'vite build',
      start: 'node build/index.js',
      lint: 'biome check .',
      typecheck: 'svelte-kit sync && svelte-check --tsconfig ./tsconfig.json',
      test: 'vitest run',
    },
    // Everything is a devDependency: adapter-node bundles devDependencies into build/, so the
    // production image needs no node_modules (only production `dependencies` stay external).
    devDependencies: {
      [`${scope}/config`]: 'workspace:*',
      [`${scope}/ui-svelte`]: 'workspace:*',
      ...Object.fromEntries(backends.map((b) => [`${scope}/${b.name}-client`, 'workspace:*'])),
      '@biomejs/biome': v['@biomejs/biome'],
      '@sveltejs/adapter-node': v['@sveltejs/adapter-node'],
      '@sveltejs/kit': v['@sveltejs/kit'],
      '@sveltejs/vite-plugin-svelte': v['@sveltejs/vite-plugin-svelte'],
      '@types/node': v['@types/node'],
      svelte: v.svelte,
      'svelte-check': v['svelte-check'],
      typescript: v.typescript,
      vite: v.vite,
      vitest: v.vitest,
    },
  })
  return tree
}

function dockerfile(ctx: AppContext): string {
  const pkg = `${ctx.scope}/${ctx.app.name}`
  const dir = `apps/${ctx.app.name}`
  const port = ctx.app.port
  // build/ is self-contained (dependencies bundled); package.json supplies "type": "module".
  return `${PNPM_BUILD_STAGE}RUN pnpm --filter ${pkg}... build

FROM node:24-alpine AS runtime
ENV NODE_ENV=production
ENV PORT=${port}
WORKDIR /app
COPY --from=build --chown=node:node /repo/${dir}/package.json ./
COPY --from=build --chown=node:node /repo/${dir}/build ./build
USER node
EXPOSE ${port}
HEALTHCHECK --interval=30s --timeout=3s --start-period=10s CMD node -e "fetch('http://127.0.0.1:' + process.env.PORT + '/').then((r) => process.exit(r.ok ? 0 : 1)).catch(() => process.exit(1))"
CMD ${JSON.stringify(['node', 'build/index.js'])}
`
}

