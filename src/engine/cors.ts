import type { AppContext } from '../plugins/types'

/** Browser origins of the frontends that use this backend: its CORS default for local dev. */
export function devCorsOrigins(ctx: AppContext): string[] {
  return ctx.stack.apps
    .filter((a) => a.kind === 'frontend' && a.port !== undefined && a.uses?.includes(ctx.app.name))
    .map((a) => `http://localhost:${a.port}`)
}

/**
 * Backend `src/generated/cors.ts` (tool-owned, so `add` refreshes it) and the commented
 * `CORS_ORIGINS` line of its `.env.example`. The app falls back to these origins when
 * CORS_ORIGINS is unset; compose and real deployments set it explicitly.
 */
export function backendCorsDefaults(ctx: AppContext): { file: string; envLine: string } {
  const origins = devCorsOrigins(ctx)
  const items = origins.map((o) => `'${o}'`)
  const oneLine = `export const DEFAULT_CORS_ORIGINS: string[] = [${items.join(', ')}]`
  const decl =
    oneLine.length <= 100
      ? oneLine
      : `export const DEFAULT_CORS_ORIGINS: string[] = [\n${items.map((i) => `  ${i},\n`).join('')}]`
  return {
    file: `// Generated by octorepo. Do not edit: regenerated by \`add\`.
// Browser origins allowed when CORS_ORIGINS is unset: the frontends that use this app.
${decl}
`,
    envLine: `# Comma-separated browser origins; unset means the frontends that use this app.
# CORS_ORIGINS=${origins.length ? origins.join(',') : 'http://localhost:3000'}
`,
  }
}
